// Bundle the xterm engine into one inline HTML document the webview loads
// with no network. Output is generated (gitignored) and rebuilt on install.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const result = await build({
  entryPoints: [`${root}src/terminal/engine/index.ts`],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  write: false,
  logLevel: "silent",
});
const js = result.outputFiles[0].text;
const css = readFileSync(`${root}node_modules/@xterm/xterm/css/xterm.css`, "utf8");
// The CSP is the last line: no network, no frames, no navigation targets;
// only the inline script and style this file writes.
const csp = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'; frame-src 'none'";
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${csp}">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${css}
html,body{margin:0;padding:0;height:100%;background:#191923;overflow:hidden}
#term{position:absolute;inset:0}
</style></head><body><div id="term"></div><script>${js}</script></body></html>`;
writeFileSync(
  `${root}src/terminal/engine/bundle.generated.ts`,
  `// Generated by scripts/build-terminal-engine.mjs. Do not edit.\nexport const TERMINAL_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`terminal engine: ${(html.length / 1024).toFixed(0)} KiB`);
